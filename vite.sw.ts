import type { Plugin } from 'vite'

/**
 * Emits /sw.js at build time: a tiny, dependency-free service worker that precaches the
 * built app shell (index.html + every hashed asset, including lazy game chunks) so the
 * app cold-launches offline after the first successful load.
 *
 * Update lifecycle: a new worker installs and then WAITS. It only takes over when the
 * page posts SKIP_WAITING (offered at the Arcade menu), so game code is never replaced
 * mid-round. The cache name embeds a hash of the asset list, so old shells are deleted
 * on activation.
 */
export function serviceWorkerPlugin(): Plugin {
  return {
    name: 'magtile-service-worker',
    apply: 'build',
    // Run after Vite's own plugins so index.html is already in the bundle and can be hashed.
    generateBundle: {
      order: 'post',
      handler(_options, bundle) {
      const assets = Object.keys(bundle).filter((f) => f !== 'sw.js').sort()
      const salt = (globalThis as { process?: { env: Record<string, string | undefined> } }).process?.env.MAGTILE_SW_SALT ?? ''
      // The version covers file names AND contents (index.html has no content hash in its name).
      let h = 5381
      const mix = (text: string) => {
        for (let i = 0; i < text.length; i++) h = ((h << 5) + h + text.charCodeAt(i)) | 0
      }
      for (const f of assets) {
        const item = bundle[f]
        mix(f)
        mix(item.type === 'chunk' ? item.code : typeof item.source === 'string' ? item.source : String(item.source.byteLength))
      }
      mix(salt)
      const version = (h >>> 0).toString(36)
      const urls = ['/', ...assets.map((f) => `/${f}`)]

      const source = `// Generated by vite.sw.ts. Do not edit.
const VERSION = ${JSON.stringify(version)}
const CACHE = 'magtile-shell-' + VERSION
const ASSETS = ${JSON.stringify(urls)}

self.addEventListener('install', (event) => {
  // No skipWaiting here: an updated worker waits until the app asks (Arcade menu).
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(ASSETS.map((u) => new Request(u, { cache: 'reload' })))),
  )
})

self.addEventListener('message', (event) => {
  if (event.data === 'SKIP_WAITING') self.skipWaiting()
  if (event.data === 'GET_VERSION' && event.source) event.source.postMessage({ type: 'VERSION', version: VERSION })
})

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('magtile-shell-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  )
})

self.addEventListener('fetch', (event) => {
  const req = event.request
  if (req.method !== 'GET') return
  const url = new URL(req.url)
  if (url.origin !== self.location.origin) return
  if (url.pathname === '/sw.js') return
  event.respondWith(
    caches.open(CACHE).then(async (cache) => {
      const hit = await cache.match(req, { ignoreSearch: req.mode === 'navigate', ignoreVary: true })
      if (hit) return hit
      if (req.mode === 'navigate') {
        const shell = await cache.match('/', { ignoreVary: true })
        if (shell) return shell
      }
      return fetch(req)
    }),
  )
})
`
      this.emitFile({ type: 'asset', fileName: 'sw.js', source })
      },
    },
  }
}
